// Writes app/public/js/np-lines.js: the family's recorded lines (Mom, Dad, the sister, Gran) for the 3D characters,
// straight from voice-lines.json (itself generated from docs/SCRIPT.md). Run after editing the script:
//   node tools/audio/np-lines.mjs
// The subtitle is the exact recorded text (no names, no placeholders). fx=downstairs lines are shouts from another room.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(here, 'voice-lines.json'), 'utf8'));
const keep = new Set(['mom', 'dad', 'sister', 'gran']);
const callouts = { 'mom-shout': 'mom', 'mom-call': 'mom', 'dad-shout': 'dad', 'sis-whine': 'sister' };
const out = {};
const aliases = {};
const displays = {};
const dialogue = {};
const directions = {};
for (const l of src.lines) {
  const text = String(l.line).replace(/\s*\|\s*$/, '').trim();
  if (/[{}]/.test(text)) throw new Error('placeholder in recorded line ' + l.id);
  if (l.callout && callouts[l.callout] !== l.character) throw new Error('wrong name call-out speaker ' + l.id);
  out[l.id] = l.callout ? [l.character, text, l.fx || null, l.callout] : l.fx ? [l.character, text, l.fx] : [l.character, text];
  if(l.dialogue)dialogue[l.id]={speaker:l.character,...l.dialogue};
  if(l.mood)directions[l.id]=l.mood;
  if(l.replaces)aliases[l.replaces]=l.id;
  if(l.display)displays[l.id]=l.display;
}
for(const [old,id]of Object.entries(aliases)){out[old]=out[id];if(directions[id])directions[old]=directions[id];}
const body = '/* np-lines: GENERATED by tools/audio/np-lines.mjs from tools/audio/voice-lines.json (docs/SCRIPT.md). Do not edit by hand.\n' +
  ' * id -> [speaker, subtitle (= the recorded text), fx, optional name call-out]. Voice files, when they exist, are audio/voice/<id>.mp3 (js/st-voice.js). */\n' +
  '(function () {\n  \'use strict\';\n  const all = Object.freeze(' + JSON.stringify(out, null, 0).replace(/\],"/g, '],\n    "') + ');\n' +
  '  window.VoiceLines = all;\n  window.NPCDialogue = Object.freeze('+JSON.stringify(dialogue)+');\n  window.VoiceDirections = Object.freeze('+JSON.stringify(directions)+');\n  window.VoiceDisplays = Object.freeze('+JSON.stringify(displays)+');\n  window.VoiceLineAliases = Object.freeze('+JSON.stringify(aliases)+');\n  window.NPCLines = Object.freeze(Object.fromEntries(Object.entries(all).filter(([,l]) => ' + JSON.stringify([...keep]) + '.includes(l[0]))));\n})();\n';
fs.writeFileSync(path.join(here, '..', '..', 'app', 'public', 'js', 'np-lines.js'), body);
console.log('np-lines.js:', Object.keys(out).length, 'lines');
