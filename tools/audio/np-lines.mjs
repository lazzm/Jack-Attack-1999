// Writes app/public/js/np-lines.js: the family's recorded lines (Mom, Dad, the sister, Gran) for the 3D characters,
// straight from voice-lines.json (itself generated from docs/SCRIPT.md). Run after editing the script:
//   node tools/audio/np-lines.mjs
// The subtitle is the exact recorded text (no names, no placeholders). fx=downstairs lines are shouts from another room.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(here, 'voice-lines.json'), 'utf8'));
const keep = new Set(['mom', 'dad', 'sister', 'gran']);
const out = {};
for (const l of src.lines) {
  if (!keep.has(l.character)) continue;
  const text = String(l.line).replace(/\s*\|\s*$/, '').trim();
  if (/[{}]/.test(text)) throw new Error('placeholder in recorded line ' + l.id);
  out[l.id] = l.fx ? [l.character, text, l.fx] : [l.character, text];
}
const body = '/* np-lines: GENERATED by tools/audio/np-lines.mjs from tools/audio/voice-lines.json (docs/SCRIPT.md). Do not edit by hand.\n' +
  ' * id -> [speaker, subtitle (= the recorded text), fx]. Voice files, when they exist, are audio/voice/<id>.mp3 (js/st-voice.js). */\n' +
  '(function () {\n  \'use strict\';\n  window.NPCLines = Object.freeze(' + JSON.stringify(out, null, 0).replace(/\],"/g, '],\n    "') + ');\n})();\n';
fs.writeFileSync(path.join(here, '..', '..', 'app', 'public', 'js', 'np-lines.js'), body);
console.log('np-lines.js:', Object.keys(out).length, 'lines');
